"""
export_dish_catalog.py
----------------------
Writes server/ai/food/dishCatalog.json: for every dish in the taxonomy, the
exact FoodRecognition item DishDetect returns when it recognises that dish
(name, local name, portion, per-100 g nutrients, diet tier, allergens, who it
suits, condition cautions, provenance), built with the same functions the
API uses (core.taxonomy, core.nutrition, core.diet, api.food).

The server uses it when the food model is unreachable and another image
model (Sarvam) names the dish: the numbers and cautions are still the ones
this project curated, never the image model's own guesses.

    python tools/export_dish_catalog.py        (run from ml/food-classifier)
Re-run whenever indian_taxonomy.json or indian_nutrition.json changes.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)

from core import taxonomy, nutrition, diet  # noqa: E402
from core.predictor import DietPredictor  # noqa: E402
from api.food import to_food_recognition  # noqa: E402

OUT = os.path.join(ROOT, '..', '..', 'server', 'ai', 'food', 'dishCatalog.json')


def entry(dish):
    meta = taxonomy.info(dish)
    tier = taxonomy.tier(dish)
    nut = nutrition.for_dish(dish, meta.get('key_ingredients'))
    result = {
        'dish': {'name': dish, 'local_name': meta.get('local_name'), 'confidence': 0.0, 'recognized': True},
        'diet': {'tier': tier, 'label': DietPredictor._label(tier), 'reliable': False},
        'nutrition': nut,
        'restrictions': diet.restrictions(dish, nut),
        'rationale': meta.get('rationale'),
        'warnings': [],
    }
    rec = to_food_recognition(result)
    return {'item': rec['items'][0], 'rationale': meta.get('rationale'), 'region': meta.get('region')}


def main():
    dishes = sorted(taxonomy.known_dishes())
    catalog = {'_comment': 'Generated by ml/food-classifier/tools/export_dish_catalog.py. Do not edit by hand.',
               'dishes': {d: entry(d) for d in dishes}}
    with open(OUT, 'w', encoding='utf-8') as f:
        json.dump(catalog, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write('\n')
    with_numbers = sum(1 for v in catalog['dishes'].values() if v['item']['nutrition']['provenance'] != 'none')
    print(f'{len(dishes)} dishes written to {os.path.normpath(OUT)} ({with_numbers} with nutrition)')


if __name__ == '__main__':
    main()
