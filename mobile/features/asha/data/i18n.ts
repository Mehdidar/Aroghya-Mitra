export function t(key: string, lang: Lang = 'en', params: Record<string, string | number> = {}): string {
  const entry = STRINGS[key];
  const template = entry ? (entry[lang] ?? entry.en) : key;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}
